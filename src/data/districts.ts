// Helper to look up canonical district by slug, name, or alias
export function findDistrict(query: string): District | undefined {
  if (!query) return undefined;
  const clean = query.trim().toLowerCase();
  
  return BIHAR_DISTRICTS.find((d) => {
    if (d.slug.toLowerCase() === clean) return true;
    if (d.name.toLowerCase() === clean) return true;
    return d.aliases.some((alias) => alias.toLowerCase().includes(clean) || clean.includes(alias.toLowerCase()));
  });
}
